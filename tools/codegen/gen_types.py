#!/usr/bin/env python3
"""Generates src/types/generated/{structs,enums}.rs from google.genai.types.

Reads pydantic model/enum metadata from the installed `google-genai` package
(pinned via requirements.txt) and emits Rust structs/enums with the same
names and snake_case field names as the Python SDK. See
specs/001-port-genai-rust/research.md R-04 and contracts/codegen.md.

DO NOT hand-edit the generated output; edit this script or
types_overrides.py instead, then re-run `generate.py --only types`.
"""

from __future__ import annotations

import enum
import inspect
import pathlib
import sys
import typing

import google.genai
from google.genai import _common, types  # type: ignore[import-untyped]

import attribution
import upstream

GENAI_VERSION = upstream.assert_supported_version()

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "src" / "types" / "generated"

HEADER = (
    f"// @generated by tools/codegen/gen_types.py from google-genai {GENAI_VERSION}. DO NOT EDIT.\n"
    + attribution.rust_attribution("gen_types.py", GENAI_VERSION)
    + "// Edit tools/codegen/gen_types.py (its EXCLUDED_CLASSES / annotation\n"
    "// mapping constants) and re-run\n"
    "// `python tools/codegen/generate.py --only types` instead.\n\n"
)

# --- classes excluded from generation -------------------------------------
#
# - `_`-prefixed classes are Python-internal "Parameters" bundles used to
#   pass method arguments around inside the SDK; the Rust API takes each
#   argument as its own function parameter instead (see contracts/public-api.md).
# - HttpOptions/HttpRetryOptions/HttpResponse are hand-written in
#   src/types/http.rs (they configure the transport layer, not a request
#   body) -- see that file's module doc.
# - DebugConfig configures the Python replay/record test harness, which
#   this crate does not implement (see research.md R-11).
# - `Enum` is `enum.Enum` leaking into the `types` module namespace, not an
#   SDK type.
EXCLUDED_CLASSES = {"HttpOptions", "HttpRetryOptions", "HttpResponse", "DebugConfig", "Enum"}
EXTERNAL_TYPES = {"HttpOptions", "HttpRetryOptions", "HttpResponse"}

# (ClassName, field_name) -> field is dropped entirely from the generated
# struct. `parsed` holds an arbitrary Python object instance (no Rust
# equivalent); the `Metric.*_fn` fields hold Python callables.
EXCLUDED_FIELDS = {
    ("GenerateContentResponse", "parsed"),
    ("Metric", "custom_function"),
    ("Metric", "parse_and_reduce_fn"),
    ("Metric", "aggregate_summary_fn"),
}

# (ClassName, field_name) -> Rust type override for fields whose Python
# annotation is a union the generic mapper cannot resolve on its own
# (mostly "ContentUnion"/"PartUnion"-shaped fields, which the Python SDK
# normalizes at call time via `_transformers.t_content`/`t_contents`).
# The override is the *inner* type (the generator still wraps it in
# `Option<...>`).
FIELD_TYPE_OVERRIDES = {
    ("CountTokensConfig", "system_instruction"): "crate::types::Content",
    ("CreateBatchJobConfig", "dest"): "crate::types::BatchJobDestination",
    ("CreateCachedContentConfig", "contents"): "Vec<crate::types::Content>",
    ("CreateCachedContentConfig", "system_instruction"): "crate::types::Content",
    ("EmbedContentBatch", "contents"): "Vec<crate::types::Content>",
    ("EmbedContentParameters", "contents"): "Vec<crate::types::Content>",
    ("GenerateContentConfig", "system_instruction"): "crate::types::Content",
    ("GenerateContentConfig", "response_schema"): "crate::types::Schema",
    ("GenerateContentConfig", "tools"): "Vec<crate::types::Tool>",
    ("GenerateContentConfig", "speech_config"): "crate::types::SpeechConfig",
    ("InlinedRequest", "contents"): "Vec<crate::types::Content>",
    ("LiveClientSetup", "system_instruction"): "crate::types::Content",
    ("LiveClientSetup", "tools"): "Vec<crate::types::Tool>",
    ("LiveConnectConfig", "system_instruction"): "crate::types::Content",
    ("LiveConnectConfig", "tools"): "Vec<crate::types::Tool>",
    ("LiveSendRealtimeInputParameters", "media"): "crate::types::Blob",
    ("LiveSendRealtimeInputParameters", "video"): "crate::types::Blob",
    ("JSONSchema", "type"): "crate::types::JsonSchemaTypeOrList",
    # `list[Metric | UnifiedMetric]`: pydantic leaves these as unresolved
    # `ForwardRef`s (see EvaluationConfig.metrics), and evaluation
    # (`Metric`/`UnifiedMetric`) is outside this crate's initial scope
    # (spec.md Assumptions); simplified to the more common `Metric` case.
    ("EvaluationConfig", "metrics"): "Vec<crate::types::Metric>",
}

RUST_RAW_IDENT_FIELDS = {"type", "ref", "enum"}


def rust_field_ident(name: str) -> str:
    if name in RUST_RAW_IDENT_FIELDS:
        return f"r#{name}"
    return name


def is_model(cls: object) -> bool:
    return inspect.isclass(cls) and issubclass(cls, _common.BaseModel) and cls is not _common.BaseModel


def is_ci_enum(cls: object) -> bool:
    # Almost every SDK enum is `CaseInSensitiveEnum`; `JSONSchemaType` is a
    # lone plain `enum.Enum` (JSON Schema's `"type"` values are
    # case-sensitive by spec). Both render identically here -- the
    # case-insensitive `From<String>` fallback is a superset of exact
    # matching, so treating both uniformly is safe.
    return inspect.isclass(cls) and issubclass(cls, enum.Enum) and cls not in (enum.Enum, _common.CaseInSensitiveEnum)


def unwrap_optional(annotation: object) -> object:
    origin = typing.get_origin(annotation)
    if origin is typing.Union:
        args = [a for a in typing.get_args(annotation) if a is not type(None)]
        if len(args) == 1:
            return args[0]
    return annotation


class UnhandledAnnotation(Exception):
    pass


# Rust types whose proto3 JSON encoding may arrive as a quoted string.
# Maps the generated field type -> its `serde_as` adapter.
INT64_LENIENT_TYPES = {
    "i64": "Option<serde_with::PickFirst<(_, serde_with::DisplayFromStr)>>",
    "Vec<i64>": "Option<Vec<serde_with::PickFirst<(_, serde_with::DisplayFromStr)>>>",
}


def map_annotation(cls_name: str, field_name: str, annotation: object) -> tuple[str, bool]:
    """Returns (rust_inner_type, is_bytes)."""
    inner = unwrap_optional(annotation)
    origin = typing.get_origin(inner)

    if inner is str:
        return "String", False
    if inner is bool:
        return "bool", False
    if inner is int:
        return "i64", False
    if inner is float:
        return "f64", False
    if inner is bytes:
        return "Vec<u8>", True
    if inner is typing.Any:
        return "serde_json::Value", False
    if inspect.isclass(inner) and inner.__module__ == "datetime":
        return "String", False

    if origin is typing.Literal:
        # A constrained set of literal strings (e.g. a routing-preference
        # enum with no dedicated Python enum type). Simplified to `String`
        # rather than generating a bespoke one-off enum per field.
        return "String", False

    if origin is list:
        (item,) = typing.get_args(inner)
        item_type, item_bytes = map_annotation(cls_name, field_name, item)
        if item_bytes:
            return f"Vec<{item_type}>", "list"
        return f"Vec<{item_type}>", False

    if origin is dict:
        key, value = typing.get_args(inner)
        if key is not str:
            raise UnhandledAnnotation(f"non-str dict key: {cls_name}.{field_name}")
        if value is typing.Any:
            return "std::collections::HashMap<String, serde_json::Value>", False
        value_type, value_bytes = map_annotation(cls_name, field_name, value)
        if value_bytes:
            raise UnhandledAnnotation(f"dict of bytes not supported: {cls_name}.{field_name}")
        return f"std::collections::HashMap<String, {value_type}>", False

    if is_model(inner) or is_ci_enum(inner):
        name = inner.__name__
        if name in EXTERNAL_TYPES:
            return f"crate::types::{name}", False
        return f"crate::types::{name}", False

    raise UnhandledAnnotation(f"{cls_name}.{field_name}: {annotation!r}")


def rust_doc_lines(text: str | None) -> list[str]:
    if not text:
        return []
    # Escape `[`/`]` so rustdoc does not interpret Python docstring prose
    # (which sometimes contains bracket notation) as broken intra-doc links.
    escaped = text.replace("[", r"\[").replace("]", r"\]")
    lines = [line.strip() for line in escaped.strip().splitlines()]
    return [f"/// {line}" if line else "///" for line in lines]


def collect_classes() -> tuple[list[tuple[str, type]], list[tuple[str, type]]]:
    all_classes = inspect.getmembers(types, inspect.isclass)
    models = [
        (name, cls)
        for name, cls in all_classes
        if is_model(cls) and name not in EXCLUDED_CLASSES and not name.startswith("_")
    ]
    enums = [
        (name, cls)
        for name, cls in all_classes
        if is_ci_enum(cls) and name not in EXCLUDED_CLASSES and not name.startswith("_")
    ]
    return sorted(models), sorted(enums)


def compute_direct_edges(models: list[tuple[str, type]]) -> dict[str, set[str]]:
    """Maps a struct name to the set of struct/enum names it references via
    a *direct* (non-Vec/non-HashMap) `Option<T>` field -- the only shape
    that requires `Box` to break a reference cycle."""
    edges: dict[str, set[str]] = {name: set() for name, _ in models}
    model_names = {name for name, _ in models}
    for name, cls in models:
        for field_name, field in cls.model_fields.items():
            if (name, field_name) in EXCLUDED_FIELDS:
                continue
            override = FIELD_TYPE_OVERRIDES.get((name, field_name))
            if override is not None:
                if override.startswith("crate::types::") and "Vec<" not in override:
                    target = override.removeprefix("crate::types::")
                    if target in model_names:
                        edges[name].add(target)
                continue
            inner = unwrap_optional(field.annotation)
            if is_model(inner) and inner.__name__ in model_names:
                edges[name].add(inner.__name__)
    return edges


def types_needing_box(models: list[tuple[str, type]]) -> set[tuple[str, str]]:
    """Returns the set of (struct_name, target_name) direct-reference edges
    that must be boxed to avoid an infinite-size type."""
    edges = compute_direct_edges(models)

    def reachable(start: str) -> set[str]:
        seen: set[str] = set()
        stack = [start]
        while stack:
            node = stack.pop()
            for nxt in edges.get(node, ()):
                if nxt not in seen:
                    seen.add(nxt)
                    stack.append(nxt)
        return seen

    reach = {name: reachable(name) for name, _ in models}
    boxed: set[tuple[str, str]] = set()
    for name, targets in edges.items():
        for target in targets:
            if target == name or name in reach.get(target, ()):
                boxed.add((name, target))
    return boxed


def render_struct(name: str, cls: type, boxed_edges: set[tuple[str, str]]) -> str:
    doc = rust_doc_lines(inspect.getdoc(cls))
    non_snake_fields = [
        field_name
        for field_name in cls.model_fields
        if (name, field_name) not in EXCLUDED_FIELDS and field_name != field_name.lower()
    ]

    lines: list[str] = []
    lines.extend(doc or [f"/// `{name}`."])
    if non_snake_fields:
        # A handful of fields (e.g. `TextResponseFormat.jsonSchema`) are not
        # snake_case in the Python SDK itself; kept verbatim for 1:1
        # fidelity rather than silently renamed. Placed on the struct
        # (rather than the field) because `#[serde_as]` re-emits the
        # struct and does not reliably preserve a field-level `#[expect]`.
        lines.append(
            '#[expect(non_snake_case, reason = "matches the Python SDK\'s own (non-snake_case) attribute name(s) for 1:1 fidelity")]'
        )
    lines.append("#[serde_with::serde_as]")
    lines.append("#[derive(Debug, Clone, PartialEq, Default, serde::Serialize, serde::Deserialize)]")
    lines.append(f"pub struct {name} {{")
    for field_name, field in cls.model_fields.items():
        if (name, field_name) in EXCLUDED_FIELDS:
            continue
        override = FIELD_TYPE_OVERRIDES.get((name, field_name))
        is_bytes = False
        if override is not None:
            rust_type = override
        else:
            try:
                rust_type, is_bytes = map_annotation(name, field_name, field.annotation)
            except UnhandledAnnotation as exc:
                raise SystemExit(f"gen_types.py: unhandled annotation: {exc}") from exc

        base_target = rust_type.removeprefix("crate::types::")
        if (name, base_target) in boxed_edges:
            rust_type = f"Box<{rust_type}>"

        field_doc = rust_doc_lines(field.description) or [f"/// `{name}.{field_name}`."]
        lines.extend(field_doc)
        # Deserialization also accepts the wire (camelCase, or otherwise
        # pydantic-aliased) key, matching Python's `populate_by_name=True`
        # + `alias_generator=to_camel`: several converters copy a
        # sub-object through without a nested `_X_to_mldev`/`_from_mldev`
        # call (e.g. `usage_metadata`), leaving its keys in wire form, and
        # pydantic accepts that transparently via the alias -- this is the
        # Rust equivalent.
        if field.alias and field.alias != field_name:
            lines.append(f'    #[serde(alias = "{field.alias}")]')
        lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
        if is_bytes == "list":
            lines.append('    #[serde_as(as = "Option<Vec<serde_with::base64::Base64>>")]')
        elif is_bytes:
            lines.append('    #[serde_as(as = "Option<serde_with::base64::Base64>")]')
        elif rust_type in INT64_LENIENT_TYPES:
            # proto3's canonical JSON mapping encodes int64/uint64 as
            # *strings* (to survive JavaScript's 2^53 precision limit), so
            # the live API returns e.g. `"sizeBytes": "15"`. Python's
            # pydantic coerces that to `int` automatically; serde does not,
            # and would fail with `invalid type: string "15", expected i64`.
            # `PickFirst` accepts either form on the wire while still
            # *serializing* as a JSON number, which is what pydantic emits
            # for outgoing requests (and which the server also accepts, since
            # proto3 parsers must take both).
            lines.append(f'    #[serde_as(as = "{INT64_LENIENT_TYPES[rust_type]}")]')
        ident = rust_field_ident(field_name)
        lines.append(f"    pub {ident}: Option<{rust_type}>,")
    lines.append("}")
    return "\n".join(lines)


def rust_enum_variant(value: str) -> str:
    parts = [p for p in value.replace("-", "_").split("_") if p]
    ident = "".join(p[:1].upper() + p[1:].lower() for p in parts)
    if not ident or ident[0].isdigit():
        ident = f"V{ident}"
    return ident


def render_enum(name: str, cls: type[enum.Enum]) -> str:
    doc = rust_doc_lines(inspect.getdoc(cls))
    members = list(cls)
    variants = [(rust_enum_variant(m.value), m.value) for m in members]

    lines: list[str] = []
    lines.extend(doc or [f"/// `{name}`."])
    lines.append("#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]")
    lines.append('#[serde(from = "String", into = "String")]')
    lines.append(f"pub enum {name} {{")
    for ident, value in variants:
        # Per-member Python docstrings are not retrievable at runtime
        # (`__doc__` only reflects the class docstring); the wire value
        # itself is the most reliable available label.
        lines.append(f"    /// `{value}`.")
        lines.append(f"    {ident},")
    lines.append("    /// An enum value not known when this crate was generated.")
    lines.append("    Unknown(String),")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {name} {{")
    lines.append("    /// The exact wire string for this value (matches the Python SDK's `.value`).")
    lines.append("    #[must_use]")
    lines.append("    pub fn as_str(&self) -> &str {")
    lines.append("        match self {")
    for ident, value in variants:
        lines.append(f'            Self::{ident} => "{value}",')
    lines.append("            Self::Unknown(value) => value,")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append(f"impl std::fmt::Display for {name} {{")
    lines.append("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
    lines.append("        f.write_str(self.as_str())")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append(f"impl From<String> for {name} {{")
    lines.append("    fn from(value: String) -> Self {")
    lines.append("        match value.to_ascii_uppercase().as_str() {")
    for ident, value in variants:
        lines.append(f'            "{value.upper()}" => Self::{ident},')
    lines.append("            _ => Self::Unknown(value),")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append(f"impl From<{name}> for String {{")
    lines.append(f"    fn from(value: {name}) -> Self {{")
    lines.append("        value.as_str().to_owned()")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    models, enums = collect_classes()
    boxed_edges = types_needing_box(models)

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    structs_path = OUT_DIR / "structs.rs"
    with structs_path.open("w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write(f"//! Generated from {len(models)} `pydantic` models in `google.genai.types`.\n\n")
        f.write("#![allow(clippy::pedantic, dead_code, rustdoc::bare_urls, reason = \"1:1 generated port of google-genai's pydantic models; pedantic-tier style lints, per-field dead-code flags, and bare-URL doc warnings don't apply to a mechanically generated public API surface whose doc comments are verbatim Python docstrings\")]\n\n")
        for name, cls in models:
            f.write(render_struct(name, cls, boxed_edges))
            f.write("\n\n")

    enums_path = OUT_DIR / "enums.rs"
    with enums_path.open("w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write(f"//! Generated from {len(enums)} `CaseInSensitiveEnum` classes in `google.genai.types`.\n\n")
        f.write("#![allow(clippy::pedantic, dead_code, rustdoc::bare_urls, reason = \"1:1 generated port of google-genai's pydantic enums; pedantic-tier style lints, per-variant dead-code flags, and bare-URL doc warnings don't apply to a mechanically generated public API surface whose doc comments are verbatim Python docstrings\")]\n\n")
        for name, cls in enums:
            f.write(render_enum(name, cls))
            f.write("\n\n")

    mod_path = OUT_DIR / "mod.rs"
    with mod_path.open("w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("//! Generated type re-exports. See `structs.rs` and `enums.rs`.\n\n")
        f.write("mod enums;\n")
        f.write("mod structs;\n\n")
        f.write("pub use enums::*;\n")
        f.write("pub use structs::*;\n")

    print(f"gen_types.py: wrote {len(models)} structs, {len(enums)} enums (google-genai {GENAI_VERSION})", file=sys.stderr)


if __name__ == "__main__":
    main()
