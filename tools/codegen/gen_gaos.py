@dataclasses.dataclass
class Param:
    py_name: str
    wire: str
    ident: str
    ref: Ref
    doc: str | None
    required: bool


@dataclasses.dataclass
class Operation:
    resource: str
    struct: str
    py_class: str
    name: str
    python: str
    verb: str
    template: str
    opid: str
    doc: str
    path_params: list[Param]
    query_params: list[Param]
    body: Param | None
    body_optional: bool
    response: Ref | None
    stream: bool
    request_class: str
    stream_response: Ref | None = None
    sample_response: object | None = None
    sample_body: object | None = None


def _const_str(node: ast.AST | None) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def parse_resources(builder: Builder) -> list[Operation]:
    ops: list[Operation] = []
    types_pkg = importlib.import_module(TYPES_PKG)
    models_pkg = importlib.import_module(MODELS_PKG)
    namespace = {sub: getattr(types_pkg, sub) for sub in RESOURCES}
    for resource, classes in RESOURCES.items():
        for filename, class_name, prefix in classes:
            tree = ast.parse((GAOS_SRC_DIR / filename).read_text(encoding="utf-8"))
            cls_node = next(c for c in tree.body if isinstance(c, ast.ClassDef) and c.name == class_name)
            impls: dict[str, ast.FunctionDef] = {}
            for fn in cls_node.body:
                if isinstance(fn, ast.FunctionDef) and fn.name not in NON_OPERATION_METHODS:
                    if any(ast.unparse(d) == "overload" for d in fn.decorator_list):
                        continue
                    impls[fn.name] = fn
            for fname, fn in impls.items():
                ops.append(extract_operation(builder, resource, class_name, prefix, fname, fn, namespace, models_pkg))
    return ops


def extract_operation(
    builder: Builder,
    resource: str,
    class_name: str,
    prefix: str,
    fname: str,
    fn: ast.FunctionDef,
    namespace: dict,
    models_pkg: pytypes.ModuleType,
) -> Operation:
    verb = template = opid = None
    accept = ""
    response_expr = None
    for node in ast.walk(fn):
        if isinstance(node, ast.Call):
            callee = ast.unparse(node.func)
            if callee == "self._build_request":
                kw = {k.arg: k.value for k in node.keywords}
                verb = _const_str(kw.get("method"))
                template = _const_str(kw.get("path"))
                accept = ast.unparse(kw["accept_header_value"]) if "accept_header_value" in kw else ""
            elif callee == "HookContext":
                kw = {k.arg: k.value for k in node.keywords}
                opid = _const_str(kw.get("operation_id"))
            elif callee == "unmarshal_json_response" and response_expr is None:
                first = ast.unparse(node.args[0])
                if not first.startswith("errors."):
                    response_expr = first
    if not (verb and template and opid):
        sys.exit(f"gen_gaos.py: cannot extract {resource}.{fname}: verb/path/operation id missing")

    opid = opid[:1].upper() + opid[1:]
    req_module = importlib.import_module(f"{MODELS_PKG}.{opid.lower()}")
    req_cls = next(
        obj
        for name, obj in vars(req_module).items()
        if inspect.isclass(obj) and name.lower() == f"{opid}Request".lower()
    )
    path_params: list[Param] = []
    query_params: list[Param] = []
    body: Param | None = None
    body_optional = False
    docs = builder.reg.class_docs.get((req_module.__name__, req_cls.__name__), {})
    placeholders = re.findall(r"\{(\w+)\}", template)
    by_alias: dict[str, Param] = {}
    for pname, finfo in req_cls.model_fields.items():
        md = next((m for m in finfo.metadata if type(m).__name__ == "FieldMetadata"), None)
        if md is None or pname == "api_version":
            continue
        ctx = (resource, req_cls.__name__, pname)
        meta = list(finfo.metadata)
        if finfo.discriminator is not None:
            meta.append(finfo)
        ref = builder.conv(finfo.annotation, meta, ctx, req_module.__name__)
        param = Param(
            py_name=pname,
            wire=finfo.alias or pname,
            ident=rust_ident(pname),
            ref=ref,
            doc=docs.get(pname),
            required=finfo.is_required(),
        )
        if md.path is not None:
            by_alias[param.wire] = param
        elif md.query is not None:
            query_params.append(param)
        elif md.request is not None:
            body = param
            body_optional = not finfo.is_required()
    path_params = [by_alias[p] for p in placeholders if p != "api_version"]
    for p in placeholders:
        if p != "api_version" and p not in by_alias:
            sys.exit(f"gen_gaos.py: {resource}.{fname}: path placeholder {p} has no request field")

    response: Ref | None = None
    if response_expr:
        obj = eval(response_expr, {}, namespace)  # noqa: S307 - dotted names from upstream source
        response = builder.conv(obj, [], (resource, opid, "response"))

    stream_response: Ref | None = None
    if "text/event-stream" in accept:
        item = re.search(r"Stream\[([\w\.]+)\]", ast.unparse(fn.returns))
        if item is None:
            sys.exit(f"gen_gaos.py: {resource}.{fname}: stream operation without Stream[...] return type")
        stream_response = builder.conv(eval(item.group(1), {}, namespace), [], (resource, opid, "event"))  # noqa: S307

    doc = ast.get_docstring(fn) or ""
    doc = re.split(r"^:param ", doc, maxsplit=1, flags=re.M)[0].strip()
    return Operation(
        resource=resource,
        struct=class_name,
        py_class=class_name,
        name=f"{prefix}{fname}",
        python=f"{resource}.{prefix.rstrip('_') + '.' if prefix else ''}{fname}",
        verb=verb,
        template=template,
        opid=opid,
        doc=doc,
        path_params=path_params,
        query_params=query_params,
        body=body,
        body_optional=body_optional,
        response=response,
        stream="text/event-stream" in accept,
        request_class=req_cls.__name__,
        stream_response=stream_response,
    )


