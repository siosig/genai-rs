def query_push(p: Param, reg: Registry) -> str:
    wire = p.wire
    ident = p.ident
    if p.ref[0] == "list":
        return f'query.push_all("{wire}", params.{ident}.as_deref());'
    return f'query.push("{wire}", params.{ident}.as_ref());'


