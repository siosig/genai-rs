#!/usr/bin/env python3
"""Generates the `_gaos` surface (Interactions, agents, environments, triggers,
webhooks, voices, credentials) from the installed `google-genai` package.

Inputs
    - reflection over every pydantic model under `google.genai._gaos.types`
      and `google.genai._gaos.models` (field list, aliases, discriminated and
      open unions, string enums written as `Literal[...]`);
    - the AST of `_gaos/<resource>.py` (HTTP verb, path template, operation id,
      stream capability, response type) cross-checked against the request
      model of the same operation (path / query / body field classification);
    - `tools/codegen/gaos_overrides.toml` (renames and the recorded list of
      fields that cannot be mapped).

Outputs (all start with the `@generated` header)
    - `src/gaos/{mod,types,models}.rs`
    - `src/gaos/resources/{agents,credentials,environments,interactions,
      triggers,voices,webhooks}.rs` and `resources/mod.rs`
    - `tests/fixtures/gaos/*.json` (+ README carrying the attribution),
      `tests/gaos/generated_ops.rs`
    - `tools/codegen/methods_gaos.toml` (read by `gen_blocking.py` and
      `gen_parity.py`)

See specs/008-python-genai-rust-conformance/contracts/gaos-generation.md.
DO NOT hand-edit the generated output; edit this script or
`gaos_overrides.toml` and re-run `generate.py --only gaos` instead.
"""

