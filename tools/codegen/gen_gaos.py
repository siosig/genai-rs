def render_resource(reg: Registry, resource: str, ops: list[Operation], models_names: dict[str, str]) -> str:
    r = Renderer(reg)
    struct = ops[0].struct if resource != "environments" else "Environments"
    uses_stream = any(o.stream for o in ops)
    parts = [
        header(),
        f"//! `client.{resource}()`: the `_gaos` `{resource}` operations. Generated from\n"
        f"//! `google/genai/_gaos/{resource}.py`.\n\n",
        ALLOW_ATTR,
        "use reqwest::Method;\n",
    ]
    if uses_stream:
        parts.append("use futures_core::Stream;\nuse futures_util::StreamExt;\n")
    errors_import = "{Error, Result}" if uses_stream else "Result"
    parts.append(f"\nuse crate::{{\n    client::Client,\n    errors::{errors_import},\n    gaos::wire,\n    types::HttpOptions,\n}};\n\n")
    parts.append(
        f"/// Handle for the `{resource}` operations (`client.{resource}()`).\n"
        "#[derive(Debug, Clone)]\n"
        f"pub struct {struct} {{\n    pub(crate) client: Client,\n    pub(crate) http_options: Option<HttpOptions>,\n}}\n\n"
        f"impl {struct} {{\n"
        "    pub(crate) fn new(client: Client) -> Self {\n        Self {\n            client,\n            http_options: None,\n        }\n    }\n\n"
        "    /// Returns a handle whose calls use `options` instead of the client's `HttpOptions`:\n"
        "    /// extra `headers`, a per-call `api_version`, `timeout`, `extra_body` or `retry_options`\n"
        "    /// (the upstream per-call `extra_headers` / `api_version` / `timeout` arguments).\n"
        "    #[must_use]\n"
        "    pub fn with_http_options(mut self, options: HttpOptions) -> Self {\n"
        "        self.http_options = Some(options);\n        self\n    }\n\n"
    )
    for op in ops:
        parts.append(render_operation(r, op, models_names))
    parts.append("}\n")
    return "".join(parts)


def op_signature_args(r: Renderer, op: Operation, models_names: dict[str, str]) -> list[tuple[str, str]]:
    args: list[tuple[str, str]] = []
    for p in op.path_params:
        args.append((p.ident, "&str"))
    if op.body is not None:
        body_ty = r.rust_type(op.body.ref, None, absolute=True)
        args.append(("body", f"Option<&{body_ty}>" if op.body_optional else f"&{body_ty}"))
    if op.query_params:
        args.append(("params", f"&crate::gaos::models::{models_names[op.opid]}"))
    return args


def render_operation(r: Renderer, op: Operation, models_names: dict[str, str]) -> str:
    out: list[str] = []
    variants = [(op.name, False)]
    if op.stream:
        variants = [(op.name, False), (f"{op.name}_stream", True)]
    for name, streaming in variants:
        args = op_signature_args(r, op, models_names)
        arg_src = "".join(f", {n}: {t}" for n, t in args)
        resp_ty = "()" if op.response is None else r.rust_type(op.response, None, absolute=True)
        if streaming:
            item_ty = r.rust_type(op.stream_response, None, absolute=True)  # type: ignore[arg-type]
            ret = f"Result<impl Stream<Item = Result<{item_ty}>> + Send + Unpin + use<>>"
        else:
            ret = f"Result<{resp_ty}>"
        doc = doc_lines(op.doc) or [f"/// `{op.python}`."]
        if streaming:
            doc.append("///")
            doc.append(f"/// Streaming variant of [`Self::{op.name}`]: requests `text/event-stream` and yields each event.")
        doc += [
            "///",
            f"/// `{op.verb} {op.template}`.",
            "///",
            "/// # Errors",
            "/// Returns [`Error::Api`](crate::errors::Error::Api) for a non-2xx response,",
            "/// [`Error::Http`](crate::errors::Error::Http) for transport failures, and",
            "/// [`Error::Json`](crate::errors::Error::Json) if the request cannot be serialized or the response cannot be decoded.",
        ]
        out.extend("    " + ln for ln in doc)
        out.append(f"    pub async fn {name}(&self{arg_src}) -> {ret} {{")
        out.append(render_body(r, op, streaming, item_ty if streaming else resp_ty))
        out.append("    }\n")
    return "\n".join(out) + "\n"


def render_body(r: Renderer, op: Operation, streaming: bool, resp_ty: str) -> str:
    tmpl = op.template
    assert tmpl.startswith("/{api_version}/"), tmpl
    rel = tmpl.removeprefix("/{api_version}/")
    fmt = re.sub(r"\{(\w+)\}", "{}", rel)
    lines: list[str] = []
    placeholders = [p for p in re.findall(r"\{(\w+)\}", rel)]
    by_wire = {p.wire: p for p in op.path_params}
    if placeholders:
        fmt_args = ", ".join(f"wire::path_segment({by_wire[ph].ident})" for ph in placeholders)
        lines.append(f'        let url_path = format!("{fmt}", {fmt_args});')
    else:
        lines.append(f'        let url_path = "{rel}";')
    path_arg = "&url_path" if placeholders else "url_path"
    stream_flag = any(p.py_name == "stream" for p in op.query_params)
    if op.query_params:
        lines.append("        let mut query = wire::Query::default();")
        for p in op.query_params:
            if p.py_name != "stream":
                lines.append("        " + query_push(p, r.reg))
        if stream_flag:
            # `stream` is a query flag on this operation; the facade always sends it
            # (`true` for the stream variant, `false` otherwise, like the Python SDK).
            lines.append(f'        query.set("stream", "{"true" if streaming else "false"}");')
        lines.append("        let query = query.finish();")
    else:
        lines.append("        let query: Option<String> = None;")
    if op.body is not None:
        if op.body_optional:
            lines.append("        let body = body.map(serde_json::to_value).transpose()?;")
        else:
            lines.append("        let body = serde_json::to_value(body)?;")
        hook = BODY_HOOKS.get((op.resource, op.name))
        if hook is not None:
            lines.append(f"        let body = {hook}(body)?;")
        if streaming and op.body is not None:
            if op.body_optional:
                lines.append("        let body = body.map(wire::with_stream_flag);")
            else:
                lines.append("        let body = wire::with_stream_flag(body);")
        body_arg = "body" if op.body_optional else "Some(body)"
    else:
        body_arg = "None"
    method = f"Method::{op.verb}"
    if streaming:
        lines.append("        let http_options = wire::stream_http_options(self.http_options.as_ref());")
        lines.append("        let events = self")
        lines.append("            .client")
        lines.append("            .http()")
        lines.append(f"            .request_stream({method}, {path_arg}, query.as_deref(), {body_arg}, Some(&http_options))")
        lines.append("            .await?;")
        lines.append(
            f"        Ok(events.map(|event| event.and_then(|value| serde_json::from_value::<{resp_ty}>(value).map_err(Error::from))))"
        )
    else:
        lines.append("        let response = self")
        lines.append("            .client")
        lines.append("            .http()")
        lines.append(f"            .request({method}, {path_arg}, query.as_deref(), {body_arg}, self.http_options.as_ref())")
        lines.append("            .await?;")
        if op.response is None:
            lines.append("        let _ = response;")
            lines.append("        Ok(())")
        else:
            lines.append("        wire::parse(&response.body)")
    return "\n".join(lines)


