def render_models_rs(reg: Registry, ops: list[Operation]) -> tuple[str, dict[str, str]]:
    r = Renderer(reg)
    parts = [
        header(),
        "//! Query-parameter structs of the `_gaos` operations (one per upstream\n"
        "//! `models.<Operation>Request` that carries query parameters). Path\n"
        "//! parameters and the request body are separate method arguments.\n\n",
        ALLOW_ATTR,
    ]
    names: dict[str, str] = {}
    for op in sorted(ops, key=lambda o: o.request_class):
        if not op.query_params:
            continue
        names[op.opid] = op.request_class
        parts.append(
            f"/// Query parameters of `{op.python}` (upstream `{op.request_class}`).\n"
            "#[derive(Debug, Clone, PartialEq, Default)]\n"
            f"pub struct {op.request_class} {{\n"
        )
        for p in op.query_params:
            parts.append("\n".join(first_doc(p.doc, f"`{p.py_name}`.", "    ")) + "\n")
            parts.append(f"    pub {p.ident}: Option<{r.rust_type(p.ref, None)}>,\n")
        parts.append("}\n\n")
    return "".join(parts), names


