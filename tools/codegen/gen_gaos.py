def toml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render_methods_toml(ops: list[Operation], reg: Registry, models_names: dict[str, str]) -> str:
    r = Renderer(reg)
    lines = [
        "# @generated by tools/codegen/gen_gaos.py. DO NOT EDIT.",
        "# Method inventory of the `_gaos` surface; read by gen_blocking.py and gen_parity.py",
        "# alongside methods.toml (see that file's header for the field meanings).",
        "",
    ]
    seen_modules: set[str] = set()
    for op in ops:
        if op.resource in seen_modules:
            continue
        seen_modules.add(op.resource)
        struct = op.struct if op.resource != "environments" else "Environments"
        lines += [
            "[[client_module]]",
            f'name = "{op.resource}"',
            f'owner = "crate::gaos::resources::{op.resource}::{struct}"',
            f'struct = "{struct}"',
            "",
        ]
    for op in ops:
        struct = op.struct if op.resource != "environments" else "Environments"
        owner = f"crate::gaos::resources::{op.resource}::{struct}"
        args = [f"{n}: {t}" for n, t in op_signature_args(r, op, models_names)]
        ret = "()" if op.response is None else r.rust_type(op.response, None, absolute=True)
        path = op.template.removeprefix("/{api_version}/")
        for streaming in ([False, True] if op.stream else [False]):
            name = f"{op.name}_stream" if streaming else op.name
            lines += [
                "[[method]]",
                f'module = "{op.resource}"',
                f'owner = "{owner}"',
                f'name = "{name}"',
                f'python = "{op.python}"',
                "args = [" + ", ".join(toml_str(a) for a in args) + "]",
                "ret = "
                + toml_str(
                    r.rust_type(op.stream_response, None, absolute=True) if streaming else ret  # type: ignore[arg-type]
                ),
                f'kind = "{"stream" if streaming else "unary"}"',
                f'path = "{path}"',
                f'http = "{op.verb}"',
                "",
            ]
    return "\n".join(lines)


