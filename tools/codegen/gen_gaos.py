def public_exports(reg: Registry, models_names: dict[str, str], ops: list[Operation]) -> dict[str, list[tuple[str, str, str]]]:
    """Per public module: list of (rust_path, rust_alias_or_empty, python_name) re-exports.

    Mirrors each upstream public module's `__all__`; Python-only shapes
    (`*Param` TypedDicts without a Rust twin) are skipped and counted.
    """
    r = Renderer(reg)
    exports: dict[str, list[tuple[str, str, str]]] = {}
    skipped: list[str] = []
    models_by_class = {v: k for k, v in models_names.items()}
    for resource in RESOURCES:
        mod = importlib.import_module(f"google.genai.{resource}")
        entries: list[tuple[str, str, str]] = []
        seen_alias: set[str] = set()
        for name in mod.__all__:
            obj = getattr(mod, name)
            rust_path = resolve_export(reg, obj, models_names)
            if rust_path is None:
                skipped.append(f"{resource}.{name}")
                continue
            base = rust_path.rsplit("::", 1)[-1]
            alias = "" if base == name else name
            if (alias or base) in seen_alias:
                continue
            seen_alias.add(alias or base)
            entries.append((rust_path, alias, name))
        exports[resource] = entries
    del models_by_class
    return exports


def resolve_export(reg: Registry, obj: object, models_names: dict[str, str]) -> str | None:
    r = Renderer(reg)
    if is_basemodel_class(obj):
        key = ("class", obj)
        if key in reg.defs:
            return r.def_path(reg.defs[key], None, True)
        return None
    if inspect.isclass(obj) and (obj.__name__.endswith("Param") or obj.__name__.endswith("TypedDict")):
        stem = re.sub(r"(Param|TypedDict)$", "", obj.__name__)
        modname = obj.__module__
        if modname.startswith(MODELS_PKG + "."):
            if stem in models_names.values():
                return f"crate::gaos::models::{stem}"
            return None
        ref = reg.by_modname.get((modname, stem))
        if ref and ref[0] == "def" and ref[1] in reg.defs:
            return r.def_path(reg.defs[ref[1]], None, True)
        return None
    sig = canon(obj)
    if sig in reg.defs:
        return r.def_path(reg.defs[sig], None, True)
    if sig[0] == "class" and ("class", sig[1]) in reg.defs:
        return r.def_path(reg.defs[("class", sig[1])], None, True)
    name = getattr(obj, "__name__", None)
    if is_alias_type(obj) or name:
        # An alias to a TypedDict-style `*Param` union has no Rust twin.
        return None
    return None


def add_signature_exports(
    reg: Registry,
    exports: dict[str, list[tuple[str, str, str]]],
    ops: list[Operation],
    models_names: dict[str, str],
) -> None:
    """Exports every type a resource method takes or returns that the upstream `__all__` omits.

    Python callers pass such values as keyword arguments or dicts and never name the
    type (`CreateInteractionRequestBody`, the update bodies, query-parameter models);
    Rust callers must name it, so it is re-exported under its own name.
    """
    by_resource: dict[str, list[Operation]] = {}
    for op in ops:
        by_resource.setdefault(op.resource, []).append(op)
    for resource, resource_ops in by_resource.items():
        text = render_resource(reg, resource, resource_ops, models_names)
        entries = exports[resource]
        known_paths = {path for path, _alias, _py in entries}
        known_names = {alias or path.rsplit("::", 1)[-1] for path, alias, _py in entries}
        known_names.add(next(iter({o.struct if resource != "environments" else "Environments" for o in resource_ops})))
        for path in sorted(set(re.findall(r"crate::gaos::(?:types|models)::[\w:]+", text))):
            name = path.rsplit("::", 1)[-1]
            if path in known_paths:
                continue
            if name in known_names:
                sys.exit(f"gen_gaos.py: cannot export {path} from crate::{resource}: the name {name} is taken")
            entries.append((path, "", name))
            known_names.add(name)


