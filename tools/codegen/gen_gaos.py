def write_text(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def check_unmapped(builder: Builder) -> int:
    recorded = builder.reg.overrides.get("unmapped", {})
    found = {key: reason for key, reason in builder.unmapped}
    missing = sorted(set(found) - set(recorded))
    stale = sorted(set(recorded) - set(found))
    if missing or stale:
        print("gen_gaos.py: gaos_overrides.toml [unmapped] is out of date.", file=sys.stderr)
        for key in missing:
            print(f'  missing: [unmapped."{key}"]  # {found[key]}', file=sys.stderr)
        for key in stale:
            print(f"  stale:   {key}", file=sys.stderr)
        sys.exit(1)
    recorded_count = builder.reg.overrides.get("unmapped_count")
    if recorded_count != len(found):
        sys.exit(
            f"gen_gaos.py: gaos_overrides.toml records unmapped_count = {recorded_count}, "
            f"but {len(found)} fields are unmapped"
        )
    if len(found) > UNMAPPED_LIMIT:
        sys.exit(f"gen_gaos.py: {len(found)} unmapped fields exceed the limit of {UNMAPPED_LIMIT}")
    return len(found)


def main() -> None:
    builder = Builder()
    builder.build()
    ops = parse_resources(builder)
    # Operation parsing may register further types (inline enums in query params).
    builder.finalize_names()
    builder.box_cycles()
    reg = builder.reg
    unmapped_count = check_unmapped(builder)

    for op in ops:
        sample_for_op(op, builder)

    models_rs, models_names = render_models_rs(reg, ops)
    exports = public_exports(reg, models_names, ops)
    add_signature_exports(reg, exports, ops, models_names)

    write_text(OUT_SRC / "types.rs", render_types_rs(reg))
    write_text(OUT_SRC / "models.rs", models_rs)
    write_text(OUT_SRC / "mod.rs", render_mod_rs(reg, exports, ops))

    by_resource: dict[str, list[Operation]] = {}
    for op in ops:
        by_resource.setdefault(op.resource, []).append(op)
    resources_mod = [header(), "//! Resource handles of the `_gaos` sub-SDK, one module per resource.\n\n", ALLOW_ATTR]
    for resource in sorted(by_resource):
        resources_mod.append(f"pub mod {resource};\n")
        write_text(OUT_RESOURCES / f"{resource}.rs", render_resource(reg, resource, by_resource[resource], models_names))
    write_text(OUT_RESOURCES / "mod.rs", "".join(resources_mod))

    # fixtures
    OUT_FIXTURES.mkdir(parents=True, exist_ok=True)
    for old in OUT_FIXTURES.glob("*.json"):
        old.unlink()
    for op in ops:
        if op.sample_response is not None:
            write_json(OUT_FIXTURES / f"{fixture_name(op)}.json", op.sample_response)
        if op.sample_body is not None:
            write_json(OUT_FIXTURES / f"{fixture_name(op, '_request')}.json", op.sample_body)
        if op.stream:
            event = stream_event_sample(op, builder)
            if event is not None:
                write_json(OUT_FIXTURES / f"{fixture_name(op, '_event')}.json", event)
    write_text(OUT_FIXTURES / "README.md", fixtures_readme())
    write_text(OUT_TESTS / "generated_ops.rs", render_ops_test(ops, builder, models_names))
    write_text(METHODS_GAOS_TOML, render_methods_toml(ops, reg, models_names))

    n_struct = sum(1 for d in reg.defs.values() if d.kind == "struct")
    print(
        f"gen_gaos.py: {len(reg.defs)} types ({n_struct} structs), {len(ops)} operations, "
        f"{unmapped_count} unmapped fields (google-genai {GENAI_VERSION})",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
