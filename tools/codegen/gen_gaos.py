class Sampler:
    """Builds deterministic sample JSON for a pydantic class (depth-limited)."""

    MAX_DEPTH = 3

    def sample_class(self, cls: type, depth: int = 0) -> dict:
        out: dict = {}
        for name, finfo in cls.model_fields.items():
            ann, meta, _ = strip(finfo.annotation, list(finfo.metadata))
            if finfo.discriminator is not None:
                meta.append(finfo)
            value = self.sample_value(ann, meta, name, depth, finfo)
            if value is not None:
                out[finfo.alias or name] = value
        return out

    def sample_value(self, ann: object, meta: list, field: str, depth: int, finfo: FieldInfo | None = None):
        ann, meta, _ = strip(ann, meta)
        if is_union(typing.get_origin(ann)):
            present = [m for m in typing.get_args(ann) if m is not NONE_TYPE]
            if len(present) == 1:
                return self.sample_value(present[0], meta, field, depth, finfo)
        sig = canon(ann, meta)
        kind = sig[0]
        if kind == "str":
            if ann is datetime.datetime:
                return "2026-01-01T00:00:00Z"
            return f"sample-{field}"
        if kind == "int":
            return 1
        if kind == "float":
            return 1.5
        if kind == "bool":
            return True
        if kind == "value":
            return {"key": "value"}
        if kind == "enum":
            return sig[1][0] if sig[1] else None
        if kind == "list":
            inner = typing.get_args(ann)[0]
            item = self.sample_value(inner, [], field, depth + 1)
            return [item] if item is not None else []
        if kind == "map":
            inner = typing.get_args(ann)[1]
            item = self.sample_value(inner, [], field, depth + 1)
            return {"key": item} if item is not None else {}
        if kind == "class":
            if depth >= self.MAX_DEPTH:
                return None
            return self.sample_class(ann, depth + 1)  # type: ignore[arg-type]
        if kind == "union":
            info = union_meta(meta)
            members = [m for m in typing.get_args(ann) if m is not NONE_TYPE]
            if info.open and info.unknown is not None:
                members = [m for m in members if m is not info.unknown]
            return self.sample_value(members[0], [], field, depth)
        return None


def dump_sample(cls: type, raw: dict) -> dict:
    """Round-trips `raw` through the upstream model so the fixture is exactly what Python emits."""
    try:
        model = cls.model_validate(raw)
        return model.model_dump(mode="json", by_alias=True, exclude_none=True)
    except Exception:  # noqa: BLE001 - fall back to the raw sample
        return raw


def pick_class(ann: object) -> type | None:
    ann, meta, _ = strip(ann, [])
    sig = canon(ann, meta)
    if sig[0] == "class":
        return sig[1]
    if sig[0] == "union":
        members = [m for m in typing.get_args(ann) if m is not NONE_TYPE]
        info = union_meta(meta)
        if info.open and info.unknown is not None:
            members = [m for m in members if m is not info.unknown]
        return pick_class(members[0])
    return None


def sample_for_op(op: Operation, builder: Builder) -> None:
    sampler = Sampler()
    try:
        _sample_for_op(op, builder, sampler)
    finally:
        # The HTTP layer sends no body for `{}` (as Python does), so there is nothing to match on.
        if op.sample_body == {}:
            op.sample_body = None


def _sample_for_op(op: Operation, builder: Builder, sampler: Sampler) -> None:
    if op.response is not None and op.response[0] == "def":
        d = builder.reg.defs[op.response[1]]
        if d.kind == "struct":
            cls = d.key[1]
            op.sample_response = dump_sample(cls, sampler.sample_class(cls))
    if op.body is not None and op.body.ref[0] == "def":
        d = builder.reg.defs[op.body.ref[1]]
        if d.kind == "struct":
            cls = d.key[1]
            op.sample_body = dump_sample(cls, sampler.sample_class(cls))
        elif d.kind in {"tagged", "untagged"} and d.variants and d.variants[0].ref[0] == "def":
            vd = builder.reg.defs[d.variants[0].ref[1]]
            if vd.kind == "struct":
                cls = vd.key[1]
                op.sample_body = dump_sample(cls, sampler.sample_class(cls))


def fixture_name(op: Operation, suffix: str = "") -> str:
    return f"{op.resource}_{snake(op.name)}{suffix}"


def write_json(path: pathlib.Path, value: object) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")


def stream_event_sample(op: Operation, builder: Builder) -> object | None:
    """First variant of the stream item union, sampled."""
    if op.stream_response is None or op.stream_response[0] != "def":
        return None
    d = builder.reg.defs[op.stream_response[1]]
    if d.kind == "tagged":
        # The crate's SSE decoder turns `{"error": ...}` payloads into `Error::Api`, so the
        # sample must be a non-error variant.
        for variant in d.variants:
            vd = builder.reg.defs[variant.ref[1]] if variant.ref[0] == "def" else None
            if vd is not None and vd.kind == "struct" and "Error" not in vd.name:
                cls = vd.key[1]
                return dump_sample(cls, Sampler().sample_class(cls))
    if d.kind == "struct":
        return dump_sample(d.key[1], Sampler().sample_class(d.key[1]))
    return None


