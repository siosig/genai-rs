def cross_check(methods: list[dict[str, Any]], method_rows: list[dict[str, str]]) -> list[str]:
    """Returns a list of human-readable failures (empty == OK)."""
    known = {(m["module"], m["name"]) for m in methods}
    failures: list[str] = []
    for row in method_rows:
        if row["status"] != "✅":
            continue
        module, name = row["module"], row["name"]
        if (module, name) in known:
            continue
        if module in NON_METHOD_ROWS:
            continue
        if (module, name) in NOT_PORTED:
            continue
        failures.append(
            f"  parity-matrix.md marks `{row['matrix_module']}.{name}` ✅ but "
            f"methods.toml has no [[method]] with module = \"{module}\", name = \"{name}\""
        )
    return failures


def main() -> None:
    client_modules, methods = load_methods()
    client_rows, method_rows = parse_matrix(PARITY_MATRIX.read_text(encoding="utf-8"))

    failures = cross_check(methods, method_rows)
    if failures:
        print(
            "gen_parity.py: parity regression -- "
            f"{len(failures)} ✅ item(s) in contracts/parity-matrix.md are missing "
            "from tools/codegen/methods.toml:",
            file=sys.stderr,
        )
        for failure in failures:
            print(failure, file=sys.stderr)
        print(
            "Add the missing [[method]] entries, or (if the method is genuinely out "
            "of scope) add a justified entry to NOT_PORTED in tools/codegen/gen_parity.py.",
            file=sys.stderr,
        )
        sys.exit(1)

    tests = collect_tests()
    document = render(client_modules, methods, client_rows, method_rows, tests)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(document, encoding="utf-8")
    print(
        f"gen_parity.py: wrote {OUT_FILE.relative_to(REPO_ROOT)} "
        f"({len(methods)} methods, {len(tests)} test fns scanned)",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
