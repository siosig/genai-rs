def parse_tables(text: str) -> list[list[list[str]]]:
    """Splits a Markdown document into tables (list of rows of cells)."""
    tables: list[list[list[str]]] = []
    current: list[list[str]] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if all(set(c) <= set("-: ") and c for c in cells):
                continue  # the `|---|---|` separator row
            current.append(cells)
        elif current:
            tables.append(current)
            current = []
    if current:
        tables.append(current)
    return tables


def status_of(cell: str) -> str:
    """First token of a status cell: `✅`, `⏭`, or `N/A`."""
    cell = cell.strip()
    for marker in ("✅", "⏭", "N/A"):
        if cell.startswith(marker):
            return marker
    return cell.split()[0] if cell else ""


def split_names(cell: str) -> list[str]:
    return [n.strip().strip("`") for n in cell.split("/") if n.strip()]


def translate_cell(cell: str) -> str:
    """English rendering of a cell quoted verbatim from parity-matrix.md.

    Cells that are already English pass through untouched; Japanese ones must
    have an entry in `MATRIX_CELL_TRANSLATIONS`, otherwise the generated
    document would leak Japanese into an English-only file.
    """
    text = MATRIX_CELL_TRANSLATIONS.get(cell.strip(), cell)
    if CJK_RE.search(text):
        sys.exit(
            f"gen_parity.py: no English translation for the parity-matrix.md cell {cell!r}; "
            "add it to MATRIX_CELL_TRANSLATIONS in tools/codegen/gen_parity.py "
            "(docs/parity.md must stay English-only)"
        )
    return text


def parse_matrix(text: str) -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    """Returns `(client_rows, method_rows)` from parity-matrix.md.

    `client_rows` are the rows of the three-column `| Python | Rust | status |`
    table; `method_rows` are the rows of the four-column
    `| module | Python method | Rust | status |` table, one per `/`-separated
    method name.
    """
    client_rows: list[dict[str, str]] = []
    method_rows: list[dict[str, str]] = []
    for table in parse_tables(text):
        header = table[0]
        if header[:1] == ["Python"] and len(header) == 3:
            for row in table[1:]:
                client_rows.append(
                    {"python": row[0], "rust": row[1], "status": status_of(row[2]), "raw_status": row[2]}
                )
        elif header[:1] == [MATRIX_MODULE_HEADER] and len(header) == 4:
            for row in table[1:]:
                module = MODULE_ALIASES.get(row[0], row[0])
                for name in split_names(row[1]):
                    method_rows.append(
                        {
                            "matrix_module": row[0],
                            "module": module,
                            "name": name,
                            "rust": row[2],
                            "status": status_of(row[3]),
                            "raw_status": row[3],
                        }
                    )
    if not client_rows or not method_rows:
        sys.exit(
            f"gen_parity.py: could not parse the expected tables out of {PARITY_MATRIX}; "
            "the contract document's table headers may have changed"
        )
    return client_rows, method_rows


