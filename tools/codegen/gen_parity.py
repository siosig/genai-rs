def rust_test_files() -> list[pathlib.Path]:
    files = [
        p
        for p in sorted((REPO_ROOT / "tests").rglob("*.rs"))
        if "fixtures" not in p.relative_to(REPO_ROOT).parts
    ]
    files += [
        p
        for p in sorted((REPO_ROOT / "src").rglob("*.rs"))
        if "#[cfg(test)]" in p.read_text(encoding="utf-8")
    ]
    return files


def collect_tests() -> list[tuple[str, str, str]]:
    """Returns `(test_id, fn_name, body)` for every `#[test]`-ish function."""
    tests: list[tuple[str, str, str]] = []
    for path in rust_test_files():
        rel = path.relative_to(REPO_ROOT).as_posix()
        text = path.read_text(encoding="utf-8")
        starts = [m.end() for m in TEST_ATTR_RE.finditer(text)]
        for idx, start in enumerate(starts):
            end = starts[idx + 1] if idx + 1 < len(starts) else len(text)
            chunk = text[start:end]
            fn = FN_RE.search(chunk)
            if fn is None:
                continue
            tests.append((f"{rel}::{fn.group(1)}", fn.group(1), chunk[fn.end() :]))
    return tests


def accessors(module: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    return ACCESSOR_OVERRIDES.get(module, ((f".{module}()",), ()))


def owner_source_paths(owner: str) -> set[str]:
    """`crate::live::music::LiveMusicSession` -> the files that may hold its
    own `#[cfg(test)]` module (`src/live/music.rs`, `src/live/music/mod.rs`)."""
    parts = owner.removeprefix("crate::").split("::")[:-1]
    stem = "src/" + "/".join(parts)
    return {f"{stem}.rs", f"{stem}/mod.rs"}


def find_tests(method: dict[str, Any], tests: list[tuple[str, str, str]]) -> list[str]:
    """Heuristic: prefer test bodies chaining `.<module>().<name>(`; fall back
    to "the module's handle is in scope and the method is called (or named in
    the test's own identifier)". A module's own `#[cfg(test)]` tests build the
    handle through a file-local helper (`models(&server)`), so for those the
    accessor requirement is replaced by "the test lives in that module's
    source file". Reported as a best-effort pointer, not as proof of
    coverage."""
    module, name = method["module"], method["name"]
    required, forbidden = accessors(module)
    own_files = owner_source_paths(method["owner"])
    chained = re.compile(
        r"(?:" + r"|".join(re.escape(acc) for acc in required) + r")"
        r"\s*\.\s*" + re.escape(name) + r"\s*\("
    )
    call = f".{name}("
    strong: list[str] = []
    weak: list[str] = []
    for test_id, fn_name, body in tests:
        in_own_file = test_id.split("::", 1)[0] in own_files
        if not in_own_file:
            if any(bad in body for bad in forbidden):
                continue
            if not any(acc in body for acc in required):
                continue
        if chained.search(body) or (in_own_file and call in body):
            strong.append(test_id)
        elif call in body or name in fn_name:
            weak.append(test_id)

    def rank(test: str) -> tuple[int, int, str]:
        path, fn_name = test.split("::", 1)
        return (
            0 if name in fn_name else 1,
            0 if path in own_files or pathlib.PurePosixPath(path).stem == module else 1,
            test,
        )

    return sorted(strong or weak, key=rank)


