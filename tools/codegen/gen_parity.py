# --- test discovery --------------------------------------------------------
#
# `(required, forbidden)` substrings identifying a module's accessor call in
# a test body. Default is `.<module>()`; `live` / `live_music` share the
# `client.live()` entry point, so they are disambiguated explicitly. The
# accessor requirement is waived for a module's own `#[cfg(test)]` tests,
# which reach the handle through a file-local helper instead (see
# `owner_source_paths`).
ACCESSOR_OVERRIDES: dict[str, tuple[tuple[str, ...], tuple[str, ...]]] = {
    "live": ((".live()",), (".music()",)),
    "live_music": ((".music()",), ()),
}

TEST_ATTR_RE = re.compile(r"#\[(?:tokio::test|test|rstest)\]")
FN_RE = re.compile(r"(?:async\s+)?fn\s+([A-Za-z0-9_]+)")

MAX_TESTS_SHOWN = 3


def load_methods() -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    data = tomllib.loads(METHODS_TOML.read_text(encoding="utf-8"))
    return data.get("client_module", []), data.get("method", [])


